'use strict';

/**
 * ЛОКАЛЬ ФОРМАТИРОВАНИЯ ПО КОДУ ЯЗЫКА — один список на решение.
 *
 * Язык (`de`) и локаль (`de-DE`) — разные вещи: первый выбирает перевод, вторая
 * решает, как выглядит число и дата. Соответствие между ними лежало копиями в
 * печати счёта и в печати прайс-листа, а когда третий потребитель (сообщение об
 * ошибке) захотел того же, список пришлось бы завести в третий раз. Добавление
 * языка интерфейса — и так не одна строка (раздел 20 архитектуры); пусть хотя бы
 * локаль правится в одном месте.
 *
 * Запасная локаль — немецкая: решение работает в Германии, и числа с точкой в
 * роли разделителя тысяч здесь читаются неверно.
 */

const LOCALES = { en: 'en-GB', ru: 'ru-RU', pl: 'pl-PL', de: 'de-DE' };
const FALLBACK = 'de-DE';

/** Локаль для кода языка (`de` → `de-DE`). */
function localeOf(lang) {
    return LOCALES[lang] || FALLBACK;
}

/**
 * Сумма словами человека: «20.050,00». Без знака валюты — его подставляет
 * тот, кто строит фразу: в одних местах это «€», в других — колонка таблицы.
 *
 * Значение из колонки `DECIMAL` приходит СТРОКОЙ, поэтому приводится числом
 * здесь, а не у вызывающего.
 */
function money(value, lang) {
    const n = Number(value);
    if (!isFinite(n)) return String(value == null ? '' : value);
    return n.toLocaleString(localeOf(lang), { minimumFractionDigits: 2, maximumFractionDigits: 2 });
}

module.exports = { LOCALES, FALLBACK, localeOf, money };
