'use strict';

/**
 * Правила оповещений по броням — ОБЪЯВЛЕНИЕ (ТЗ оповещений §5).
 *
 * ФАЙЛ ГРУЗЯТ ДВА ПРОЦЕССА — главный (форма, сохранение) и форкнутый воркер
 * планировщика, который выполняет проведение и суточный проход. Поэтому модуль
 * обязан быть ЧИСТОЙ ФАБРИКОЙ без побочных эффектов: ни регистраций, ни
 * подключений, ни чтения настроек на уровне модуля.
 *
 * Регистрация в `init.js` для этого НЕ ГОДИТСЯ: `init.js` выполняет только
 * главный процесс, и в воркере правила не существовало бы — пересчёт молча
 * ничего не делал бы. Та же причина, по которой так объявлены обработчики
 * проведения (`posting.handlers.js`) и типы регламентных задач.
 *
 * Сами функции живут в `hooks/alerts.js` — здесь только объявление: код, уровень
 * важности, таблица и поводы пересчёта.
 */

module.exports = function (modelsDB, Utilities) {
    const rules = require('./hooks/alerts')(modelsDB, Utilities);

    return {
        // ВЫСТАВЛЕНО БОЛЬШЕ, ЧЕМ ЗАКАЗАНО — деньги и § 17 Abs. 1 UStG, то есть
        // `error`: без корректировки счёта НДС останется должен по бумаге,
        // которой уже нет в учёте.
        'booking.overInvoiced': {
            severity: 'error',
            table: 'bookings',
            build: rules.buildOverInvoiced
        },

        // ГОСТЬ ВЫЕХАЛ, А СЧЁТ НЕ ВЫСТАВЛЕН — `warning`: это не ошибка, а
        // забытое дело, и называть его ошибкой значит приучить не читать
        // красное. Два повода пересчёта сразу: время (вчера не было — сегодня
        // есть) и движения (счёт выставлен — пометка обязана исчезнуть сейчас,
        // а не через сутки).
        // НЕТ ЦЕНЫ — `warning`: бронь сохранена и верна, не хватает цены в
        // прайс-листе; без неё счёт недоберёт денег. Пересчёт — при каждом
        // проведении брони (повод по умолчанию — движения).
        'booking.missingPrices': {
            severity: 'warning',
            table: 'bookings',
            build: rules.buildMissingPrices
        },

        'booking.notInvoiced': {
            severity: 'warning',
            table: 'bookings',
            timeDependent: true,
            select: rules.selectDeparted,
            build: rules.buildNotInvoiced
        }
    };
};
