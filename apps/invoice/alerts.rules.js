'use strict';

/**
 * Правила оповещений по счёту — ОБЪЯВЛЕНИЕ (ТЗ оповещений §5, §15).
 *
 * ФАЙЛ ГРУЗЯТ ДВА ПРОЦЕССА — главный и форкнутый воркер планировщика. Поэтому
 * модуль обязан быть ЧИСТОЙ ФАБРИКОЙ без побочных эффектов; регистрация в
 * `init.js` не годится — его выполняет только главный процесс.
 *
 * Сами функции живут в `hooks/alerts.js`.
 */

module.exports = function (modelsDB, Utilities) {
    const rules = require('./hooks/alerts')(modelsDB, Utilities);

    return {
        // ПРЕДУПРЕЖДЕНИЯ РАСЧЁТА. Уровень `warning`: услуга, не попавшая в счёт,
        // это недостача денег, которую человек обязан увидеть, но она не
        // нарушение закона и не требует встречного документа.
        //
        // `onMovements: false` — правило порождается ЗАПОЛНЕНИЕМ, а не
        // проведением (причина — в `hooks/alerts.js`), и переписывается только в
        // пределах своего кода, не задевая того, что записало проведение.
        'invoice.fillWarnings': {
            severity: 'warning',
            table: 'invoices',
            onMovements: false,
            build: rules.buildFillWarnings
        }
    };
};
