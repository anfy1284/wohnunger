'use strict';

/**
 * ПРАВИЛО ОПОВЕЩЕНИЙ СЧЁТА: предупреждения расчёта (ТЗ оповещений §15).
 *
 * ── Что здесь переделано и зачем ─────────────────────────────────────────────
 * Раньше это были ОДНОРАЗОВЫЕ сообщения: `_skippedNotice` собирал строки
 * «услуга не попала в счёт» и показывал их диалогом при заполнении. Увидел их
 * тот, кто случайно оказался у экрана в этот момент; не увидел — они пропали
 * вместе с окном, а недостача денег в счёте осталась.
 *
 * Теперь это ОПОВЕЩЕНИЯ: они висят на счёте, видны значком в журнале, попадают
 * в обработку «Проверка документов» — и переписываются ровно тогда, когда счёт
 * заполняют заново.
 *
 * ── Почему правило порождается ЗАПОЛНЕНИЕМ, а не проведением ─────────────────
 * Причина не в удобстве. Пересчитывать состав брони по уже ВЫСТАВЛЕННОМУ счёту
 * нельзя: справочники с тех пор правили, и правило показало бы владелице
 * предупреждение про услугу, которую она изменила ПОСЛЕ выставления и в этом
 * счёте всё равно исправить не может (исправление выставленного счёта — это
 * корректировка, отдельный документ). Поэтому правило объявлено
 * `onMovements: false`, а данные получает от того, кто его вызвал
 * (`ctx.input.skipped`) — от расчёта, который только что их и посчитал.
 *
 * Следствие, которое надо знать: счёт, созданный «на основании» брони, получает
 * эти оповещения при первом же «Заполнить». В момент создания сообщение
 * показывается диалогом, как и раньше, — записать оповещение там попросту некуда,
 * документа в базе ещё нет (и это правильно: передумал и закрыл окно — в базе не
 * осталось ничего).
 */

module.exports = function (modelsDB, Utilities) {

    /**
     * Ключ текста по причине пропуска. Тот же набор причин, что был у
     * `addSkipped`: расчёт их и называет, а здесь они только переводятся в
     * оповещения.
     */
    const REASON_KEYS = {
        auto:         'service_skipped_auto',
        noprice:      'service_skipped_no_price',
        manual:       'service_manual_quantity_differs',
        // Не только услуги: сюда же попадают вид гостя с заявленной, но не
        // заведённой ценой и комната без цены на такое число гостей.
        guestnoprice: 'guest_type_no_price',
        roomnoprice:  'room_no_price'
    };

    /**
     * ПРЕДУПРЕЖДЕНИЯ РАСЧЁТА — по одному оповещению на причину.
     *
     * Порядок строк ОБЯЗАН быть детерминированным: он и есть ключ сопоставления
     * при перезаписи (ТЗ §7). Расчёт отдаёт причины в порядке обхода состава
     * брони, который сам детерминирован, но полагаться на это нельзя —
     * сортируем явно, по тексту причины и названию услуги.
     *
     * Подстановки `dir`/`field` едут КЛЮЧАМИ (`{ i18n: … }`), а не словами:
     * оповещение переводится в момент показа, на языке читателя, и готовое слово
     * осталось бы на языке того, кто нажал «Заполнить».
     */
    async function buildFillWarnings(doc, ctx) {
        const skipped = (ctx && ctx.input && ctx.input.skipped) || [];
        if (!Array.isArray(skipped) || !skipped.length) return [];

        // Одна и та же причина по одной и той же услуге — одна строка.
        const seen = new Set();
        const items = [];
        for (const s of skipped) {
            if (!s) continue;
            const reason = REASON_KEYS[s.reason] ? s.reason : 'noprice';
            const key = reason + '|' + (s.service || '');
            if (seen.has(key)) continue;
            seen.add(key);
            items.push({ sortKey: key, reason, service: s.service || '', vars: s.vars || {} });
        }
        items.sort((a, b) => a.sortKey.localeCompare(b.sortKey));

        return items.map(it => ({
            text: REASON_KEYS[it.reason],
            vars: Object.assign({
                service: it.service,
                // Сообщение обязано показать, ГДЕ лежит правило, а не просто
                // сослаться на него: названия справочника и реквизита берём из
                // ТЕХ ЖЕ ключей, что и сам интерфейс.
                dir: { i18n: 'services' },
                field: { i18n: 'quantity_formula' },
                gtDir: { i18n: 'guest_types' },
                gtField: { i18n: 'room_rate_mode' }
            }, it.vars),
            // Действие — сам счёт: человек читает оповещение в журнале или в
            // обработке, и первое, что ему нужно, это открыть документ и нажать
            // «Заполнить» ещё раз.
            action: {
                kind: 'openRecord',
                app: 'invoice',
                params: { table: 'invoices', uid: doc.UID },
                caption: 'invoice_alert_open'
            }
        }));
    }

    return { buildFillWarnings, REASON_KEYS };
};
